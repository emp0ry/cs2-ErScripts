import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
const read = file => readFileSync(file,'utf8'), sha = value => createHash('sha256').update(value).digest('hex');
const main = read('dist/index.html');
const ids = [...main.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size,'No duplicate IDs');
for(const id of ['top','main','features','motion','how','responsibility','downloads','setup']) assert(ids.includes(id),`Preserve #${id}`);
assert(main.includes('data-download href="https://github.com/emp0ry/cs2-ErScripts/releases/latest"'),'No-script release link');
assert(main.includes('-conclearlog -condebug +bind scancode104 exec erscripts1'),'Exact launch options');
assert(!/id="capture-[^"]+"[^>]*\bhidden/.test(main),'No-script captures remain accessible');
assert(!/<video[^>]*\bautoplay/.test(main),'No autoplay captures');
for(const title of ['Does external mean approved?','Where should I use it?','Does it change game files?']) assert(main.includes(title),'Retain usage responsibility');
const baseline = JSON.parse(read('design/baseline.json'));
for(const file of ['docs/CNAME','docs/img/icon.ico']) assert.equal(sha(readFileSync(resolve('..',file))),baseline[file],`Retain ${file}`);
for(const page of ['index','404']) {
  const html = read(`dist/${page}.html`);
  assert(!html.includes('@include'),'All partials resolved');
  assert.equal((html.match(/<h1\b/g)||[]).length,1,'One primary heading');
  for(const tag of ['description','og:title','og:image','og:image:width','og:image:height','og:image:alt','twitter:card','theme-color']) assert(html.includes(`="${tag}"`),`${page}: ${tag}`);
  const policy = html.match(/http-equiv="Content-Security-Policy" content="([^"]+)"/)[1];
  assert(!/unsafe-inline|unsafe-eval/.test(policy),'Restrict inline executable scripts');
  for(const [,script] of html.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) assert(policy.includes(`'sha256-${createHash('sha256').update(script).digest('base64')}'`),'Exact CSP hash');
  for(const [,asset] of html.matchAll(/(?:src|href|poster|data-src)="(\/(?!\/)[^"?#]+)"/g)) assert(existsSync(resolve('dist',asset.slice(1))),`${page}: missing ${asset}`);
  for(const [,id] of html.matchAll(/href="#([^"]+)"/g)) assert(html.includes(`id="${id}"`),`${page}: missing #${id}`);
  assert(!/fonts\.googleapis\.com|fonts\.gstatic\.com/.test(html),'Local font only');
  for(const [,link] of html.matchAll(/(<a\b[^>]*target="_blank"[^>]*>)/g)) assert(link.includes('noopener'),'External tabs use noopener');
}
const png=readFileSync('dist/site/social-preview.png');assert.equal(png.readUInt32BE(16),1200);assert.equal(png.readUInt32BE(20),630);
for(const file of JSON.parse(read('pages-files.json'))) assert(readFileSync(resolve('dist',file)).equals(readFileSync(resolve('../docs',file))),`Matching Pages output: ${file}`);
console.log('Output checks pass: anchors, fallback links, exact setup command, metadata/CSP, local assets, retained domain/icon, and matching Pages output.');
